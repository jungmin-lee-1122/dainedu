/** 접수 상태 */
export type EventStatus = "접수중" | "접수예정" | "마감";

export type DainEvent = {
  /** 주소에 쓰이는 고유 번호 — /event/1 처럼 붙습니다. 중복되면 안 됩니다. */
  id: string;
  /** 분류 배지 — 설명회 / 공개특강 / 이벤트 */
  kind: "설명회" | "공개특강" | "이벤트";
  /** 목록·상세에 크게 보이는 제목 */
  title: string;
  /** 제목 위 한 줄 소개 */
  lead: string;
  /** 대상 배지 — 고1, 고2, 고3, N수, 학부모 등 */
  targets: string[];
  /** 일시 — 사람이 읽는 문구 */
  date: string;
  /** 정렬·마감 판정용 (YYYY-MM-DD HH:mm) */
  startAt: string;
  /** 장소 */
  place: string;
  /** 장소 상세 (층·관 등) */
  placeDetail?: string;
  /** 정원 안내 문구 */
  capacity: string;
  status: EventStatus;
  /** 상세 페이지 본문 문단 */
  body: string[];
  /** 진행 순서 — 시간 / 내용 */
  program: { time: string; desc: string }[];
  /** 강사·진행자 (없으면 생략) */
  speakers?: { name: string; role: string }[];
  /** 유의사항 */
  notice: string[];
};

