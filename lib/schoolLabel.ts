// ═══════════════════════════════════════════════════════════
//  강사 카드에 쓰는 짧은 학력 표기
//
//  카드에서는 "졸업" 같은 군더더기를 덜어 한 줄에 들어가게 합니다.
//  상세 페이지에는 관리자에 입력한 내용이 그대로 나옵니다.
// ═══════════════════════════════════════════════════════════
export function shortSchool(v?: string) {
  if (!v) return "";
  return v
    .replace(/\s*졸업\s*(?=[·,/]|$)/g, " ") // "… 졸업" · "… 졸업 · …" 에서 졸업만 제거
    .replace(/\s*[·/]\s*/g, " · ")          // 가운뎃점·빗금은 앞뒤 한 칸
    .replace(/\s*,\s*/g, ", ")              // 쉼표는 뒤에만 한 칸
    .replace(/\s*[·,]\s*$/, "")             // 끝에 남은 구분기호 정리
    .replace(/\s{2,}/g, " ")
    .trim();
}
