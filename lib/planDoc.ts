/** 로드맵 한 칸 — from/to 는 months 배열의 번째(0부터) */
export type Bar = {
  from: number;
  to: number;
  text?: string;
  /** main = 채운 띠, line = 테두리만 (수업 없는 과제 과정 등) */
  tone?: "main" | "line";
};

export type PlanDoc = {
  id: string;
  /** 탭에 보일 짧은 이름 */
  tab: string;
  year: string;
  subject: string;
  target: string;
  teacher: string;
  tagline?: string;
  /** 이력서형 상단에서 인물을 키우거나 줄이는 배율 (1 = 그대로).
      얼굴 크기는 전원 290 으로 맞춰져 있지만, 실루엣 폭이 사람마다 달라
      혼자 서 있는 화면에서는 작아 보이는 분이 생깁니다. 그때만 씁니다. */
  heroZoom?: number;

  /* 학력·약력은 상세페이지 위쪽 프로필 카드에 이미 나오므로
     계획서 본문에서는 그리지 않습니다. 원본 자료 기록용으로만 남겨 둡니다. */
  edu?: string[];
  careerNow: string[];
  careerPast?: string[];

  roadmap: {
    months: string[];
    rows: { label: string; bars: Bar[] }[];
  };

  steps: {
    no: string;
    name: string;
    period?: string;
    books?: string[];
    goal: string;
    detail?: string;
    /** extra = 보조 과정 (EBS·모평 대비 등) */
    tone?: "main" | "extra";
  }[];

  weekly: { label: string; value: string; note?: string }[];
  care: { label: string; desc: string }[];
  notes: string[];

  /** 03·04 칸의 제목을 선생님 자료에 맞게 바꿀 때만 씁니다(없으면 기본 제목).
      예) 주간 운영표가 없는 자료 → 03 을 "학습 콘텐츠" 로 */
  heads?: {
    weekly?: { en: string; title: string; lead: string };
    care?: { en: string; title: string; lead: string };
  };
};

