export function findPlan(id?: string) {
  return PLANS.find((p) => p.id === id) ?? PLANS[0];
}

/** 선생님 이름으로 찾기 — 강사 상세페이지에서 씁니다. 없으면 null */
export function planDocByName(name?: string): PlanDoc | null {
  const k = name ? name.replace(/\s+/g, "") : "";
  return PLANS.find((p) => p.teacher === k) ?? null;
}
